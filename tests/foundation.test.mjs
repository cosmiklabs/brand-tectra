import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {verify} from '../vendor/brand/scripts/vendor.mjs';
import {loadBaseline} from '../vendor/brand/scripts/generate-tokens.mjs';
import {expectedExtends, brandRelease} from '../vendor/brand/scripts/family.mjs';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const vendored=path.join(root,'vendor/brand');
const lock=JSON.parse(fs.readFileSync(path.join(vendored,'brand.lock.json'),'utf8'));

test('the vendored foundation matches its lock',()=>{
 const result=verify(vendored);
 assert.deepEqual(result.problems,[]);
 assert.equal(lock.repository,'cosmiklabs/brand');
 assert.match(lock.tag,/^v\d+\.\d+\.\d+$/);
 assert.equal(`v${brandRelease(vendored).version}`,lock.tag,'vendored package.json names the locked tag');
});

test('tokens/family.json extends the vendored baseline',()=>{
 const family=JSON.parse(fs.readFileSync(path.join(root,'tokens/family.json'),'utf8'));
 assert.equal(family.extends,expectedExtends(loadBaseline(vendored)));
});

test('the family build resolves the vendored baseline, not a sibling checkout',()=>{
 const css=fs.readFileSync(path.join(root,'tokens/tectra.css'),'utf8');
 assert.ok(css.startsWith(`/* Cosmik · Tectra `));
 assert.ok(css.split('\n')[0].includes(`Generated by @cosmiklabs/brand ${lock.tag.slice(1)} scripts/family.mjs from tokens/family.json`));
});

test('a changed vendored file fails verification',t=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'brand-tectra-vendor-'));
 t.after(()=>fs.rmSync(dir,{recursive:true,force:true}));
 fs.cpSync(vendored,dir,{recursive:true});
 fs.appendFileSync(path.join(dir,'kits/cosmik/tokens/cosmik.css'),'\n');
 assert.ok(verify(dir).problems.some(p=>p.startsWith('modified: kits/cosmik/tokens/cosmik.css')));
});
